"""Report on Flipper captures: patterns, mixed recordings, duplicates, timings.

Usage::

    python3 -m tools.analyze_captures captures/original
    python3 -m tools.analyze_captures captures/original --json
    python3 -m tools.analyze_captures captures/original \\
        --emit-esphome esphome/lamp-commands.generated.yaml [--check]

All timings are in µs. Highs and lows are reported as positive magnitudes;
``gap`` keeps its negative sign, matching the capture convention.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

from tools.lumos_captures import FRAME_BITS, Frame, checksum_ok, frames, parse_sub

TIMING_KEYS = ("short_high", "long_high", "short_low", "long_low", "sync_high", "gap")

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = REPO_ROOT / "captures" / "commands.json"
GENERATED_HEADER = (
    "# GENERATED by tools/analyze_captures.py --emit-esphome from captures/commands.json."
    " Do not edit by hand."
)
MIN_CLEAN_FRAMES = 10
DEFAULT_WAIT_TIME_MS = 0  # the code already ends with the measured inter-frame gap


class GeneratorError(Exception):
    """Raised when the manifest cannot be turned into safe transmit codes."""


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _median(values: list[int]) -> int:
    return int(round(statistics.median(values)))


def median_timings(clean: list[Frame]) -> dict[str, int]:
    """Median µs timings over clean frames that share one pattern.

    Highs/lows are positive magnitudes; ``gap`` is negative. Frames at end of
    file (no gap) are skipped for the gap median only.
    """
    buckets: dict[str, list[int]] = {key: [] for key in TIMING_KEYS}
    for frame in clean:
        for bit_index in range(FRAME_BITS):
            high = frame.pulses[2 * bit_index]
            low = -frame.pulses[2 * bit_index + 1]
            bit = (frame.value >> (FRAME_BITS - 1 - bit_index)) & 1
            if bit:
                buckets["long_high"].append(high)
                buckets["short_low"].append(low)
            else:
                buckets["short_high"].append(high)
                buckets["long_low"].append(low)
        buckets["sync_high"].append(frame.pulses[-1])
        if frame.gap is not None:
            buckets["gap"].append(frame.gap)
    return {key: _median(values) for key, values in buckets.items() if values}


def analyze_file(path: Path) -> dict:
    """Analyze one ``.sub`` file and return a JSON-serialisable report."""
    sub = parse_sub(str(path))
    all_frames = frames(sub)
    clean = [f for f in all_frames if f.value is not None]
    rejected = [f for f in all_frames if f.value is None]

    counts = Counter(f.value for f in clean)
    # Sort by count descending, then by value so ties are deterministic.
    ordered = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    patterns = [{"pattern": f"{value:08X}", "count": count} for value, count in ordered]
    dominant = ordered[0][0] if ordered else None

    reasons = Counter(_reason_kind(f.reject_reason) for f in rejected)

    return {
        "file": path.name,
        "sha256": _sha256(path),
        "duplicates": [],
        "frequency": sub.frequency,
        "preset": sub.preset,
        "total_frames": len(all_frames),
        "clean_frames": len(clean),
        "rejected_frames": len(rejected),
        "reject_reasons": dict(sorted(reasons.items())),
        "patterns": patterns,
        "dominant": f"{dominant:08X}" if dominant is not None else None,
        "dominant_count": counts[dominant] if dominant is not None else 0,
        "mixed": len(counts) > 1,
        "timings": median_timings([f for f in clean if f.value == dominant]),
    }


def _reason_kind(reason: str) -> str:
    """Collapse a reject reason to its category so the histogram stays short."""
    for kind in ("length", "sign", "pulse", "pair", "sync", "checksum"):
        if reason.startswith(kind):
            return kind
    return reason


def analyze_dir(directory: Path) -> list[dict]:
    """Analyze every ``*.sub`` in ``directory``, sorted by file name."""
    reports = [analyze_file(p) for p in sorted(directory.glob("*.sub"))]
    by_hash: dict[str, list[str]] = {}
    for report in reports:
        by_hash.setdefault(report["sha256"], []).append(report["file"])
    for report in reports:
        report["duplicates"] = [n for n in by_hash[report["sha256"]] if n != report["file"]]
    return reports


def format_table(reports: list[dict]) -> str:
    """Render reports as a human-readable text table."""
    lines = []
    header = f"{'File':34} {'Clean':>5} {'Rej':>4} {'Dominant':9} {'Mixed':5}  Other patterns / duplicates"
    lines.append(header)
    lines.append("-" * len(header))
    for r in reports:
        others = ", ".join(f"{p['pattern']}×{p['count']}" for p in r["patterns"][1:]) or "—"
        dup = f"  (same bytes as {', '.join(r['duplicates'])})" if r["duplicates"] else ""
        lines.append(
            f"{r['file']:34} {r['clean_frames']:>5} {r['rejected_frames']:>4} "
            f"{(r['dominant'] or '—'):9} {('yes' if r['mixed'] else 'no'):5}  {others}{dup}"
        )
    lines.append("")
    lines.append("Median timings of dominant pattern (µs): short_high long_high short_low long_low sync_high gap")
    for r in reports:
        t = r["timings"]
        values = " ".join(f"{t.get(k, '—'):>6}" for k in TIMING_KEYS)
        lines.append(f"  {r['file']:34} {values}")
    return "\n".join(lines)


def build_raw_code(value: int, timings: dict[str, int]) -> list[int]:
    """Build one frame for ``remote_transmitter.transmit_raw``.

    Returns 66 integers in µs (positive = carrier on, negative = off): 32 bit
    pairs MSB first using the measured median ``timings``, then
    ``sync_high``, then the (negative) ``gap``. Never copies recorded pulses.
    """
    code: list[int] = []
    for bit_index in range(FRAME_BITS - 1, -1, -1):
        if (value >> bit_index) & 1:
            code += [timings["long_high"], -timings["short_low"]]
        else:
            code += [timings["short_high"], -timings["long_low"]]
    code += [timings["sync_high"], timings["gap"]]
    return code


def _validate_command(cmd: dict, reports: dict[str, dict]) -> int:
    """Check one manifest entry and return its pattern as an int."""
    cid = cmd.get("id", "<missing id>")
    for key in ("id", "source", "pattern", "label", "icon", "expose", "verified"):
        if key not in cmd:
            raise GeneratorError(f"{cid}: manifest entry is missing {key!r}")
    try:
        value = int(cmd["pattern"], 16)
    except ValueError:
        raise GeneratorError(f"{cid}: pattern {cmd['pattern']!r} is not hex") from None
    if not checksum_ok(value):
        raise GeneratorError(f"{cid}: pattern {cmd['pattern']} fails checksum")
    report = reports.get(cmd["source"])
    if report is None:
        raise GeneratorError(f"{cid}: source {cmd['source']} not found among captures")
    if report["dominant"] != f"{value:08X}":
        raise GeneratorError(
            f"{cid}: pattern {cmd['pattern']} is not the dominant pattern of "
            f"{cmd['source']} (dominant is {report['dominant']})"
        )
    if report["dominant_count"] < MIN_CLEAN_FRAMES:
        raise GeneratorError(
            f"{cid}: {cmd['source']} has fewer than {MIN_CLEAN_FRAMES} clean frames "
            f"of {cmd['pattern']} ({report['dominant_count']})"
        )
    if cmd["expose"] and cmd["id"].startswith("unknown"):
        raise GeneratorError(f"{cid}: unknown commands must never be exposed")
    return value


def render_esphome(manifest: dict, reports: list[dict] | dict[str, dict]) -> str:
    """Render the ESPHome ``button:`` package for every exposed command.

    ``reports`` is :func:`analyze_dir` output (list or dict keyed by file
    name). Every manifest entry is validated, exposed or not; any problem
    raises :class:`GeneratorError`. Output is deterministic.
    """
    if isinstance(reports, list):
        reports = {r["file"]: r for r in reports}
    commands = manifest.get("commands")
    if not isinstance(commands, list):
        raise GeneratorError("manifest must contain a 'commands' list")

    seen: set[str] = set()
    buttons: list[str] = []
    for cmd in commands:
        value = _validate_command(cmd, reports)
        if cmd["id"] in seen:
            raise GeneratorError(f"{cmd['id']}: duplicate id in manifest")
        seen.add(cmd["id"])
        if not cmd["expose"]:
            continue

        timings = reports[cmd["source"]]["timings"]
        code = build_raw_code(value, timings)
        times = cmd.get("repeat", "${tx_repeat}")
        wait_ms = cmd.get("wait_time_ms", DEFAULT_WAIT_TIME_MS)
        timing_note = ", ".join(f"{k} {timings[k]}" for k in TIMING_KEYS)
        code_lines = ",\n".join(
            "              " + ", ".join(str(v) for v in code[i : i + 16])
            for i in range(0, len(code), 16)
        )
        buttons.append(
            "\n".join(
                [
                    f"  # {cmd['id']}: {cmd['pattern']} from {cmd['source']}"
                    f" (verified: {str(cmd['verified']).lower()})",
                    f"  # median timings (us): {timing_note}",
                    "  - platform: template",
                    f"    id: cmd_{cmd['id']}",
                    f"    name: {json.dumps(cmd['label'], ensure_ascii=False)}",
                    f"    icon: {json.dumps(cmd['icon'])}",
                    "    on_press:",
                    "      - remote_transmitter.transmit_raw:",
                    "          transmitter_id: tx",
                    "          code: [",
                    code_lines,
                    "            ]",
                    "          repeat:",
                    f"            times: {times}",
                    f"            wait_time: {wait_ms}ms",
                ]
            )
        )

    lines = [
        GENERATED_HEADER,
        "# One decoded frame per command, rebuilt from measured median timings.",
        "# Regenerate: python3 -m tools.analyze_captures captures/original"
        " --emit-esphome esphome/lamp-commands.generated.yaml",
    ]
    if buttons:
        lines.append("button:")
        lines.append("\n".join(buttons))
    return "\n".join(lines) + "\n"


def _emit(args: argparse.Namespace, reports: list[dict]) -> int:
    try:
        manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
        text = render_esphome(manifest, reports)
    except (OSError, json.JSONDecodeError, GeneratorError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    target: Path = args.emit_esphome
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != text:
            print(f"{target} is out of date; regenerate it with --emit-esphome", file=sys.stderr)
            return 1
        print(f"{target} is up to date")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("capture_dir", type=Path, help="directory containing .sub files")
    parser.add_argument("--json", action="store_true", help="print machine-readable JSON")
    parser.add_argument(
        "--emit-esphome", type=Path, metavar="PATH", help="write ESPHome buttons for exposed commands"
    )
    parser.add_argument(
        "--check", action="store_true", help="with --emit-esphome: exit 1 if PATH is out of date"
    )
    parser.add_argument(
        "--manifest", type=Path, default=DEFAULT_MANIFEST, help="command manifest (JSON)"
    )
    args = parser.parse_args(argv)

    if not args.capture_dir.is_dir():
        parser.error(f"{args.capture_dir} is not a directory")
    if args.check and not args.emit_esphome:
        parser.error("--check requires --emit-esphome PATH")

    reports = analyze_dir(args.capture_dir)
    if args.emit_esphome:
        return _emit(args, reports)
    if args.json:
        print(json.dumps(reports, indent=2, ensure_ascii=False))
    else:
        print(format_table(reports))
    return 0


if __name__ == "__main__":
    sys.exit(main())
